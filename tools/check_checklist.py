#!/usr/bin/env python3
"""Validate and roll up the Hustle & Heir asset checklist corpus.

The checklist lives in docs/asset-checklist/*.md. Every trackable deliverable is a
markdown checkbox line in the canonical form:

    - [ ] `ASSET-ID` — Human readable description. [S] [P0]

    status  : [ ] open, [x] done, [-] deferred/wontfix
    id      : upper-case, dash-separated, registered prefix (see PREFIXES)
    source  : [S] specified in the original brief, [D] derived/expanded here
    prio    : [P0] vertical slice, [P1] alpha, [P2] beta/launch

The script is the project's own check over the checklist: it fails on malformed or
duplicate IDs, fails if the brief's numeric requirements are not met, and fails if
the roll-up block committed in the index is stale.

Usage:
    python3 tools/check_checklist.py            # validate + print roll-up
    python3 tools/check_checklist.py --write    # ...and refresh the roll-up block in the index
    python3 tools/check_checklist.py --check    # fail if the committed roll-up is stale
    python3 tools/check_checklist.py --csv OUT  # export every item to CSV
"""

