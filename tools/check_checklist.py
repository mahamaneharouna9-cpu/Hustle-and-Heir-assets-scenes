# --------------------------------------------------------------------------- #
# roll-up
# --------------------------------------------------------------------------- #
def rollup(items: list[Item]) -> str:
    by_domain = group(items, lambda i: i.domain)
    by_prefix = group(items, lambda i: i.prefix)
    out = [ROLLUP_START, ""]
    out.append("## Progress roll-up")
    out.append("")
    total = len(items)
    done = sum(1 for i in items if i.status == "done")
    deferred = sum(1 for i in items if i.status == "deferred")
    p0 = sum(1 for i in items if i.pri == "P0")
    spec = sum(1 for i in items if i.src == "S")
    out.append(
        f"**{total} tracked assets** across {len(by_domain)} domains and "
        f"{len(by_prefix)} categories. "
        f"{done} done / {total - done - deferred} open / {deferred} deferred. "
        f"{p0} are P0 (vertical slice) and {spec} are specified in the original brief."
    )
    out.append("")
    out.append("| Domain | Categories | Items | P0 | Done | % |")
    out.append("| --- | ---: | ---: | ---: | ---: | ---: |")
    for dom in DOMAIN_ORDER:
        di = by_domain.get(dom, [])
        if not di:
            continue
        d = sum(1 for i in di if i.status == "done")
        pct = f"{round(100 * d / len(di))}%" if di else "-"
        out.append(
            f"| {dom} | {len({i.prefix for i in di})} | {len(di)} | "
            f"{sum(1 for i in di if i.pri == 'P0')} | {d} | {pct} |"
        )
    out.append(
        f"| **Total** | **{len(by_prefix)}** | **{total}** | **{p0}** | **{done}** | "
        f"**{round(100 * done / total) if total else 0}%** |"
    )
    out.append("")
    out.append("### By category")
    out.append("")
    out.append("| ID prefix | Category | Items | P0 | P1 | P2 | Done |")
    out.append("| --- | --- | ---: | ---: | ---: | ---: | ---: |")
    for dom in DOMAIN_ORDER:
        for pfx in sorted(by_prefix, key=lambda p: (DOMAIN_ORDER.index(PREFIXES[p][0]) if PREFIXES.get(p, ("?",))[0] in DOMAIN_ORDER else 99, p)):
            if PREFIXES.get(pfx, ("?",))[0] != dom:
                continue
            pi = by_prefix[pfx]
            out.append(
                f"| `{pfx}` | {PREFIXES[pfx][1]} | {len(pi)} | "
                f"{sum(1 for i in pi if i.pri == 'P0')} | {sum(1 for i in pi if i.pri == 'P1')} | "
                f"{sum(1 for i in pi if i.pri == 'P2')} | {sum(1 for i in pi if i.status == 'done')} |"
            )
    out.append("")
    out.append(ROLLUP_END)
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="rewrite the roll-up block in the index")
    ap.add_argument("--check", action="store_true", help="fail if the committed roll-up is stale")
    ap.add_argument("--csv", metavar="PATH", help="export all items to CSV")
    args = ap.parse_args()

    if not DOCS.is_dir():
        print(f"missing checklist dir: {DOCS}", file=sys.stderr)
        return 2

    errors: list[str] = []
    items = parse(errors)
    if not items:
        errors.append("no checklist items found")

    print(f"parsed {len(items)} checklist items from {DOCS.relative_to(ROOT)}")
    for name, ok, actual in build_assertions(items):
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + ("" if ok else f"  -> {actual}"))
        if not ok:
            errors.append(f"brief requirement not met: {name} (actual: {actual})")

    if args.csv:
        dest = Path(args.csv)
        dest.parent.mkdir(parents=True, exist_ok=True)
        with dest.open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(["id", "domain", "category", "status", "priority", "source", "file", "line", "description"])
            for it in items:
                w.writerow([it.id, it.domain, PREFIXES.get(it.prefix, ("", ""))[1],
                            it.status, it.pri, it.src, it.file, it.line, it.body])
        try:
            shown = dest.resolve().relative_to(ROOT)
        except ValueError:
            shown = dest
        print(f"wrote {len(items)} rows -> {shown}")

    if args.write or args.check:
        text = INDEX.read_text(encoding="utf-8")
        block = rollup(items)
        if ROLLUP_START not in text or ROLLUP_END not in text:
            print("index is missing the ROLLUP markers", file=sys.stderr)
            return 2
        head, _, rest = text.partition(ROLLUP_START)
        _, _, tail = rest.partition(ROLLUP_END)
        new = head + block + tail
        if args.write:
            if new != text:
                INDEX.write_text(new, encoding="utf-8")
                print("updated roll-up in", INDEX.relative_to(ROOT))
            else:
                print("roll-up already current")
        elif new != text:
            errors.append("roll-up in docs/asset-checklist/README.md is stale; run tools/check_checklist.py --write")

    if errors:
        print(f"\n{len(errors)} problem(s):", file=sys.stderr)
        for e in errors:
            print("  -", e, file=sys.stderr)
        return 1
    print("\nOK: checklist is well-formed and satisfies every numeric requirement in the brief.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
